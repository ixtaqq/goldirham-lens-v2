"""Write requirements.txt for the Vercel webhook: core dependencies only, pinned by uv.lock.

Run with --check in CI to fail when requirements.txt is stale.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "requirements.txt"
HEADER = "# Generated by scripts/export_webhook_requirements.py from uv.lock. Do not edit.\n"


def _uv() -> list[str]:
    if "UV" in os.environ:  # set by `uv run`
        return [os.environ["UV"]]
    if shutil.which("uv"):
        return ["uv"]
    return [sys.executable, "-m", "uv"]


def exported() -> str:
    result = subprocess.run(  # noqa: S603 - fixed uv arguments
        [
            *_uv(),
            "export",
            "--frozen",
            "--no-dev",
            "--no-default-groups",
            "--no-hashes",
            "--no-emit-project",
            "--no-header",
            "--no-annotate",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    lines = [line for line in result.stdout.splitlines() if line and not line.startswith("#")]
    return HEADER + "\n".join(lines) + "\n"


def main() -> int:
    content = exported()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != content:
            print("requirements.txt is stale: run `uv run poe webhook-reqs`", file=sys.stderr)
            return 1
        print("requirements.txt is up to date")
        return 0
    TARGET.write_text(content, encoding="utf-8")
    print(f"wrote {TARGET.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
